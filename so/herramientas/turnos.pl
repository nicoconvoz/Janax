#!/usr/bin/perl
# Generates the test of the scheduler's turn (so/nucleo/planificador.inc) against exact mathematics: for
# each case (D, s, c in sixteenths) the expected turn is the least integer t >= D + 1 with
# t * (16 t - 16 D - c) >= c * s, computed with big integers (no rounding anywhere).
# Usage: turnos.pl > escalon0/pruebas/41_turnos.jsm
use strict; use warnings; use Math::BigInt;
srand(29);
sub esperado {
  my ($d, $s, $c) = map Math::BigInt->new($_), @_;
  my $min = $d + 1;
  return $min if $c->is_zero;
  my $a = $d * 16 + $c;                       # 16 t^2 - a t - c s = 0
  my $disc = $a * $a + $c * $s * 64;
  my $t = ($a + $disc->copy->bsqrt) / 32;      # near the root, then exact
  $t -= 1 while $t > 1 && ($t - 1) * (($t - 1) * 16 - $a) >= $c * $s;
  $t += 1 while $t * ($t * 16 - $a) < $c * $s;
  return $t < $min ? $min : $t;
}
sub carga {                                   # Janax lines that load a 64-bit value into a register
  my ($r, $v) = @_;
  my $h = Math::BigInt->new($v)->as_hex; $h =~ s/^0x//; $h = ('0' x (16 - length $h)) . $h;
  my @p = map { hex substr($h, $_ * 4, 4) } 0 .. 3;
  ("jldi $r, 0", map(sprintf("jshi $r, 0%04Xh", $_), @p));
}
my @casos = ([0, 0, 0], [5, 100, 0], [0, 0, 128], [0, 0, 1], [0, 0, 15], [0, 0, 16], [0, 0, 17],
             [0, 1, 1], [3, 0, 128], [0, 1000, 128], [1000, 0, 128], [1000000, 1000000, 128],
             [0, 2**40, 128], [2**40, 2**40, 128], [2**45, 3, 4000], [7, 2**50, 1000]);
for (1 .. 200) {
  my $d = int(rand(2) < 1 ? rand(1000) : rand(2**40));
  my $s = int(rand(2) < 1 ? rand(1_000_000) : rand(2**44));
  my $c = int(rand(2) < 1 ? rand(256) : rand(4096));
  push @casos, [$d, $s, $c];
}
print "; espera: 0000000000000000\n";
print "; Generated by so/herramientas/turnos.pl: the scheduler's turn against exact mathematics, ",
      scalar(@casos), " cases.\n; j0 = how many cases gave a different turn.\n";
print "include '../janax.inc'\njldi j10, 0\njldi j11, 1\n";
my $n = 0;
for my $k (@casos) {
  my ($d, $s, $c) = @$k; $n++;
  print map("$_\n", carga('j1', $d), carga('j2', $s), carga('j3', $c), 'jcall turno', carga('j8', esperado($d, $s, $c)));
  print "jsub j8, j0, j8\njjz j8, caso_$n\njadd j10, j10, j11\ncaso_$n:\n";
}
print "jor j0, j10, j10\njhalt\ninclude '../../so/nucleo/planificador.inc'\n";
