#!/usr/bin/perl
# Generates the test of the turn by priority (cuanto in so/nucleo/planificador.inc) against exact
# mathematics: t = ceil(c * p / (1 - p)), p in 65536ths, c in sixteenths, at least 1; p = 1 is 2^62.
# Usage: cuantos.pl > escalon0/pruebas/43_cuantos.jsm
use strict; use warnings; use Math::BigInt;
srand(43);
sub esperado {
  my ($p, $c) = map Math::BigInt->new($_), @_;
  return Math::BigInt->new(2)**62 if $p >= 65536;   # 1 or more: until it ends
  my $den = (65536 - $p) * 16;
  my $t = ($c * $p + $den - 1) / $den;
  return $t < 1 ? Math::BigInt->new(1) : $t;
}
sub carga {
  my ($r, $v) = @_;
  my $h = Math::BigInt->new($v)->as_hex; $h =~ s/^0x//; $h = ('0' x (16 - length $h)) . $h;
  ("jldi $r, 0", map(sprintf("jshi $r, 0%04Xh", hex substr($h, $_ * 4, 4)), 0 .. 3));
}
my @casos = ([70000, 16], [131072, 128], [32768, 16], [32768, 80], [64881, 16], [64881, 128], [65535, 16], [65536, 16],
             [65536, 0], [1, 1], [65535, 4095], [6554, 160], [58982, 4800]);
push @casos, [int rand 65537, int rand 8192] for 1 .. 60;
print "; espera: 0000000000000000\n; Generated by so/herramientas/cuantos.pl: the turn by priority against exact mathematics, ",
      scalar(@casos), " cases.\n; j0 = how many cases gave a different turn.\ninclude '../janax.inc'\njldi j10, 0\njldi j11, 1\n";
my $n = 0;
for my $k (@casos) {
  my ($p, $c) = @$k; $n++;
  print map "$_\n", carga('j1', $p), carga('j3', $c), 'jcall cuanto', carga('j8', esperado($p, $c)),
    'jsub j8, j0, j8', "jjz j8, caso_$n", 'jadd j10, j10, j11', "caso_$n:";
}
print "jor j0, j10, j10\njhalt\ninclude '../../so/nucleo/planificador.inc'\n";
