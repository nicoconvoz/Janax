#!/usr/bin/perl
# Generates the test of the sheet of turns (hoja in so/nucleo/planificador.inc) against exact mathematics:
# for each scenario (cabins with their service, some rowed by another rower, c and how many turns), the
# expected sheet simulates one rower with least attained service and the turn rule, with big integers.
# Usage: hojas.pl > escalon0/pruebas/42_hojas.jsm
use strict; use warnings; use Math::BigInt;
srand(31);
my $SOLO = Math::BigInt->new(2)**62;
sub turno {                                   # the least t >= D + 1 with t * (16 t - 16 D - c) >= c * s
  my ($d, $s, $c) = map Math::BigInt->new($_), @_;
  my $min = $d + 1;
  return $min if $c->is_zero;
  my $a = $d * 16 + $c;
  my $t = ($a + ($a * $a + $c * $s * 64)->bsqrt) / 32;
  $t -= 1 while $t > 1 && ($t - 1) * (($t - 1) * 16 - $a) >= $c * $s;
  $t += 1 while $t * ($t * 16 - $a) < $c * $s;
  return $t < $min ? $min : $t;
}
sub hoja {                                    # -> list of [id, turn]
  my ($cab, $c, $k) = @_;
  my @s = map Math::BigInt->new($_->[0]), @$cab;
  my @out;
  while ($k-- > 0) {
    my ($elegido, $otros);
    for my $i (0 .. $#$cab) {
      if (!$cab->[$i][2] && (!defined $elegido || $s[$i] < $s[$elegido])) {
        $otros = $s[$elegido] if defined $elegido && (!defined $otros || $s[$elegido] < $otros);
        $elegido = $i;
      } elsif (!defined $otros || $s[$i] < $otros) {
        next if defined $elegido && $i == $elegido;
        $otros = $s[$i];
      }
    }
    last unless defined $elegido;
    if (!defined $otros) { push @out, [$cab->[$elegido][1], $SOLO]; last }
    my $d = $otros - $s[$elegido]; $d = Math::BigInt->new(0) if $d < 0;   # never below 0
    my $t = turno($d, $s[$elegido], $c);
    push @out, [$cab->[$elegido][1], $t];
    $s[$elegido] += $t;
  }
  return @out;
}
sub carga {
  my ($r, $v) = @_;
  my $h = Math::BigInt->new($v)->as_hex; $h =~ s/^0x//; $h = ('0' x (16 - length $h)) . $h;
  ("jldi $r, 0", map(sprintf("jshi $r, 0%04Xh", hex substr($h, $_ * 4, 4)), 0 .. 3));
}
my @casos = (
  [[[0, 0, 0]], 0, 4],                                  # alone
  [[[0, 0, 0], [0, 1, 0]], 0, 6],                       # two, c = 0: they take turns at D + 1
  [[[0, 0, 0], [0, 1, 0]], 128, 8],                     # two, c = 8 instructions
  [[[5, 0, 0], [5, 1, 0], [5, 2, 0]], 48, 9],           # three equal: ties go to the lower id
  [[[100, 0, 0], [0, 1, 1]], 128, 3],                   # the other one is rowed: it only counts as next
  [[[0, 0, 1], [0, 1, 1]], 128, 3],                     # everyone is rowed: no sheet
  [[[1000, 3, 0], [10, 7, 0], [500, 9, 1]], 64, 5],
  [[[0, 0, 0], [1, 1, 0]], 0, 1],
);
for (1 .. 40) {
  my $n = 1 + int rand 6; my @cab; my $id = 0;
  for (1 .. $n) { $id += 1 + int rand 3; push @cab, [int(rand(2) < 1 ? rand(10000) : rand(2**40)), $id, rand(5) < 1 ? 1 : 0] }
  push @casos, [\@cab, int rand 512, 1 + int rand 12];
}
print "; espera: 0000000000000000\n";
print "; Generated by so/herramientas/hojas.pl: the sheet of turns against exact mathematics, ", scalar(@casos),
      " scenarios.\n; j0 = how many scenarios gave a different sheet.\n";
print "include '../janax.inc'\njldi j14, 0\njldi j13, 1\njldi j1, 0\njst j1, j14, 1000h\n";
my $n = 0;
for my $caso (@casos) {
  my ($cab, $c, $k) = @$caso; $n++;
  my @e = hoja($cab, $c, $k);
  my @l = (carga('j1', scalar @$cab), 'jst j1, j14, 0', carga('j1', $c), 'jst j1, j14, 8', carga('j1', $k), 'jst j1, j14, 16');
  my $p = 32;
  for my $x (@$cab) {
    my $id = Math::BigInt->new($x->[1]); $id += Math::BigInt->new(2)**63 if $x->[2];
    push @l, carga('j1', $x->[0]), "jst j1, j14, $p", carga('j1', $id), 'jst j1, j14, ' . ($p + 8);
    $p += 16;
  }
  push @l, 'jcall limpiar', 'jcall hoja', 'jldi j14, 0', 'jldi j13, 1', carga('j1', scalar @e), "jsub j1, j0, j1", "jjnz j1, mal_$n";
  for my $x (@e) {
    push @l, "jld j2, j14, $p", carga('j1', $x->[0]), 'jsub j1, j2, j1', "jjnz j1, mal_$n";
    push @l, 'jld j2, j14, ' . ($p + 8), carga('j1', $x->[1]), 'jsub j1, j2, j1', "jjnz j1, mal_$n";
    $p += 16;
  }
  push @l, "jjmp bien_$n", "mal_$n:", 'jld j1, j14, 1000h', 'jadd j1, j1, j13', 'jst j1, j14, 1000h', "bien_$n:";
  print map "$_\n", @l;
}
print "jld j0, j14, 1000h\njhalt\n";
print "limpiar:                        ; every register at 0 but the return, as the kernel leaves them\n";
print map("jldi j$_, 0\n", 0 .. 15), "jret\n";
print "include '../../so/nucleo/planificador.inc'\n";
