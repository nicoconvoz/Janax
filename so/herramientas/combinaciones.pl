#!/usr/bin/perl
# Every combination of every Janax instruction (Capitan: "a program with all the possible combinations, so
# you know it is the same byte by byte"). A word is the union of independent fields (op, rd, ra, imm16), so
# this covers every bit of every field and every crossing between fields:
#   - every register combination of each instruction (16 x 16 x 16 for the three-register ones);
#   - the 65,536 values of the immediate (and of the jump distance), with every register bit at 1 (j15), so
#     a negative value that spills into the register bits shows up.
# Immediates are written in decimal in the first half and in hexadecimal in the second one, so both ways of
# writing a number are covered too. A source holds at most 32,768 lines (it must fit the assembler's 1 MiB).
# Usage: combinaciones.pl <folder> <path of janax.inc as the sources will include it>
use strict; use warnings;
my ($dir, $inc) = @ARGV;
die "usage: combinaciones.pl <folder> <janax.inc>\n" unless defined $inc;
mkdir $dir;

sub source {                      # source <name>, <lines...>
  my ($name, @lines) = @_;
  open my $f, '>', "$dir/$name.jsm" or die "$dir/$name.jsm: $!";
  print $f "; Generated by so/herramientas/combinaciones.pl: $name\ninclude '$inc'\n", map("$_\n", @lines);
  close $f;
}
sub hex16 { sprintf '0%04Xh', $_[0] }
my @r = map "j$_", 0 .. 15;

# three registers
for my $op (qw(jadd jsub jmul jdiv jshl jshr jsar jand jor jxor)) {
  source("alu_$op", map { my $d = $_; map { my $a = $_; map "$op $d, $a, $_", @r } @r } @r);
}
# register and immediate: every register, then the 65,536 immediates in two halves
for my $op (qw(jldi jshi)) {
  source("inm_${op}_a", (map "$op $_, 0", @r), map "$op j15, $_", -32768 .. -1);
  source("inm_${op}_b", map "$op j15, " . hex16($_), 0 .. 32767);
}
# memory: every register pair, then the immediates
for my $op (qw(jld jst jldb jstb)) {
  source("mem_${op}_a", (map { my $d = $_; map "$op $d, $_, 0", @r } @r), map "$op j15, j15, $_", -32768 .. -1);
  source("mem_${op}_b", map "$op j15, j15, " . hex16($_), 0 .. 32767);
}
# jumps: every distance, written as $ plus the bytes to the target (distance d = words from the next one)
sub target { my $bytes = 4 * $_[0] + 4; $bytes < 0 ? "\$ - " . -$bytes : "\$ + $bytes" }
for my $op (qw(jjmp jcall)) {
  source("salto_${op}_a", map "$op " . target($_), -32768 .. -1);
  source("salto_${op}_b", map "$op " . target($_), 0 .. 32767);
}
for my $op (qw(jjz jjnz)) {
  source("salto_${op}_a", (map "$op $_, \$", @r), map "$op j15, " . target($_), -32768 .. -1);
  source("salto_${op}_b", map "$op j15, " . target($_), 0 .. 32767);
}
# the rest: jsys, jhost, no operands, while, jfirst, dd
my @sizes = (0, 1, 8, 32767, 32768, 32769, 65535, 65536, 0x123456, 0x7FFFFFFF, -1, -32768);
my @words = (0, 1, -1, 0x7FFFFFFF, -0x80000000, 0x80000000, 0xFFFFFFFF, 0x12345678);
source('otras',
  (map { my $d = $_; map "jsys $d, $_", @r } @r),
  (map { my $d = $_; map "jhost $d, $_", @r } @r),
  'jhalt', 'jret',
  (map { ("jwhile $_", 'jldi j0, 1', 'jwend', "jwhilez $_", 'jwend') } @r),
  (map { my $d = $_; map "jfirst $d, $_", @sizes } @r),
  (map "dd $_", @words));
