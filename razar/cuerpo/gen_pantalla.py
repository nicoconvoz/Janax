"""Generates pantalla.jsm: the scene as a list of rectangles, the cloud header computed here, one routine per job."""
W, H = 160, 100
HDR = 0x1000; BITS = HDR + 28; RGB = BITS + W * H // 8; TOTAL = 28 + W * H // 8 + 3 * W * H
assert RGB < 0x8000 and RGB + 3 * W * H < 0x10000
escena = [  # x0, y0, x1, y1 (exclusive), r, g, b
 ("the desktop", 0, 0, 160, 100, 0x1f, 0x4e, 0x5a),
 ("Razar's window: shadow", 23, 13, 113, 79, 0x10, 0x2a, 0x30),
 ("border", 20, 10, 110, 76, 0x22, 0x22, 0x2a),
 ("body", 21, 18, 109, 75, 0xf4, 0xec, 0xe0),
 ("title bar", 21, 11, 109, 18, 0x2f, 0x5f, 0xa8),
 ("close", 101, 12, 107, 17, 0xd0, 0x40, 0x40),
 ("minimize", 94, 12, 100, 17, 0xe0, 0xb0, 0x30),
 ("a little tower: 1", 28, 26, 36, 34, 0xff, 0x6b, 0x6b),
 ("a little tower: 6", 36, 26, 44, 34, 0x4d, 0x96, 0xff),
 ("a little tower: 3", 52, 26, 60, 34, 0xff, 0xd9, 0x3d),
 ("a little tower: 8", 60, 26, 68, 34, 0x6b, 0xcb, 0x77),
 ("a button", 28, 62, 58, 70, 0xc8, 0xc8, 0xd0),
 ("Luma's window: shadow", 93, 47, 153, 93, 0x10, 0x2a, 0x30),
 ("border", 90, 44, 150, 90, 0x22, 0x22, 0x2a),
 ("body", 91, 51, 149, 89, 0xe8, 0xf4, 0xec),
 ("title bar", 91, 45, 149, 51, 0x3a, 0x9a, 0x5a),
 ("close", 142, 46, 147, 50, 0xd0, 0x40, 0x40),
 ("the taskbar", 0, 94, 160, 100, 0x2a, 0x2a, 0x33),
 ("start", 2, 95, 18, 99, 0x6b, 0xcb, 0x77),
]
cabeza = b"NUBE" + bytes([3]) + b"\x00\x00\x80\x3f" + b"\x00\x00" + bytes([1]) + b"\x00\x00\x80\x3f" + bytes(8) + W.to_bytes(2, "little") + H.to_bytes(2, "little")
assert len(cabeza) == 28
L = []; o = L.append
o("; Janax draws its first screen: a desktop with Razar's and Luma's windows and a taskbar, one particle per cell.")
o("; It is written as a particle cloud in Gotching's format (.nube version 3, no bones, one level, %dx%d)," % (W, H))
o("; so the same reader that draws the creatures can draw it. File: \"pantalla.nube\". Generated by gen_pantalla.py.")
o("; Layout of room 0: 100h the request queue, 200h the label, 0%Xh the cloud (28 bytes of header, %d of cells, %d of colour)." % (HDR, W * H // 8, 3 * W * H))
o("include '../../escalon0/janax.inc'")
o("jfirst j1, 10000h")
o("jldi j9, 0                      ; j9 stays 0")
o("jldi j14, 0%Xh                   ; the header, byte by byte" % HDR)
for b in cabeza: o("jldi j2, 0%Xh" % b); o("jcall emit")
o("jldi j14, 0%Xh                   ; every cell holds a particle: all bits set" % BITS)
o("jldi j2, 0FFh")
o("jldi j12, %d" % (W * H // 8))
o("bits:")
o("  jcall emit")
o("  jldi j13, 1")
o("  jsub j12, j12, j13")
o("  jjnz j12, bits")
for nombre, x0, y0, x1, y1, r, g, b in escena:
    o("jldi j1, %d                      ; %s" % (x0, nombre))
    o("jldi j2, %d" % y0); o("jldi j3, %d" % x1); o("jldi j4, %d" % y1)
    o("jldi j5, 0%Xh" % r); o("jldi j6, 0%Xh" % g); o("jldi j7, 0%Xh" % b)
    o("jcall rect")
o("jldi j14, 200h                  ; the label: pantalla.nube")
for b in b"pantalla.nube": o("jldi j2, 0%Xh" % b); o("jcall emit")
o("jldi j3, 100h                   ; open, write the cloud, close")
o("jldi j4, 1"); o("jldi j5, 32")
o("jldi j10, 4"); o("jldi j11, 200h"); o("jldi j12, 13"); o("jcall tocar")
o("jadd j7, j13, j9                ; the handle")
o("jshl j10, j7, j5"); o("jldi j8, 6"); o("jor j10, j10, j8")
o("jldi j11, 0%Xh" % HDR); o("jldi j12, 0"); o("jshi j12, 0%Xh               ; %d bytes" % (TOTAL, TOTAL)); o("jcall tocar")
o("jadd j0, j13, j9                ; j0 = bytes written")
o("jshl j10, j7, j5"); o("jldi j8, 7"); o("jor j10, j10, j8"); o("jcall tocar")
o("jhalt")
o("emit:                           ; one byte (j2) at j14, and j14 moves on")
o("  jstb j2, j14, 0"); o("  jldi j13, 1"); o("  jadd j14, j14, j13"); o("  jret")
o("rect:                           ; paints x j1..j3, y j2..j4 (exclusive) with colour j5 j6 j7")
o("  jadd j8, j2, j9")
o("ry:")
o("  jsub j10, j4, j8"); o("  jjz j10, rdone"); o("  jadd j11, j1, j9")
o("rx:")
o("  jsub j10, j3, j11"); o("  jjz j10, rnext")
o("  jldi j12, %d" % W); o("  jmul j12, j8, j12"); o("  jadd j12, j12, j11")
o("  jldi j13, 3"); o("  jmul j12, j12, j13"); o("  jldi j13, 0%Xh" % RGB); o("  jadd j12, j12, j13")
o("  jstb j5, j12, 0"); o("  jstb j6, j12, 1"); o("  jstb j7, j12, 2")
o("  jldi j13, 1"); o("  jadd j11, j11, j13"); o("  jjmp rx")
o("rnext:")
o("  jldi j13, 1"); o("  jadd j8, j8, j13"); o("  jjmp ry")
o("rdone:")
o("  jret")
o("tocar:                          ; one request (j10 type, j11 a, j12 b) -> j13 answer")
o("  jst j4, j3, 0"); o("  jst j10, j3, 8"); o("  jst j11, j3, 16"); o("  jst j12, j3, 24")
o("  jsys j14, j3"); o("  jld j13, j3, 32"); o("  jret")
open(r"E:\Janax\razar\cuerpo\pantalla.jsm", "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("ok", len(L), "lines, total", TOTAL)
