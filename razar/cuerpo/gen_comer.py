"""Generates comer_nubes.jsm: Razar's own forms (formas.jsm, the same generator, gen_formas.py) fed on Gotching's
particle clouds (Capitan: "that it feeds on Gotching's clouds as food, and from there starts to build whatever it
wants, whenever it wants").

It eats when IT wants: when its living loop runs out of novelty (the moment formas.jsm would calm), it is hungry and
eats the next uneaten cloud. Eating a cloud (all of it in jsm, at run time):
  1. the meal arrives: its finest level, fitted to a plate of two rooms, falls in as particles;
  2. digestion: the cloud fitted to a room is described in Razar's own language (MDL): the recipe over its organ
     alphabet, with its bricks, whose grown body best explains the creature's silhouette, cost = recipe bits + bits
     to name every wrong cell. A first-improvement climb from the forms it has; the meal's particles take the shape
     of the best recipe so far;
  3. it keeps that recipe and the meal's palette (its few dominant colours, by counting), learns bricks from all its
     meals' recipes (greedy MDL pair merging, as razar/jueces/torrecitas.py), and opens a round of creation over
     what is new: the meal's recipe in place of a form, crossed with each form, and the new bricks inserted;
  4. the meal's particles flow into the first form that changed in that round (or, if none, into the form it
     reminded it of) and that form takes its colour.
With nothing left to eat and nothing new, it calms for ever (0 CPU) until a gesture.

Python generates the program and nothing else: it never reads a cloud (the clouds are private and are read at run
time, request 37). Janax cannot list a folder of the host, so comer_nubes.sh writes the list of their paths into
Razar's folder ("despensa"); the program carries no creature name."""
