def layout():
    _s()
    base = NS["ROOM"]
    regs = {}
    at = [base]
    def reg(name, size, align=8):
        a = (at[0] + align - 1) // align * align
        regs[name] = a; at[0] = a + size
    reg("DREG", NS["PREG"]); reg("DGB", 512); reg("DBMP", 512); reg("TBMP", 512); reg("BBMP", 512)
    reg("MPART", PCELLS * MSZ); reg("PACC", PCELLS * 40); reg("RACC", NS["ROOMCELLS"] * 16)
    reg("BINS", 64 * 32); reg("MCOLS", 64 * 24); reg("BODYL", NS["ROOMCELLS"] * 8)
    reg("CMR", 65536 * 8); reg("CMP", 65536 * 8)        # a column map per u16 column (the cloud's width is a u16)
    reg("LINEB", 1024); reg("XBMP", 512); reg("FORMER", FORMER_N * 8)
    reg("HASHC", (1 << HBITS_C) * 8, 4096)
    NS.update(regs)
    NS["HBITS"] = HBITS_C; NS["HN"] = 1 << HBITS_C; NS["HASH"] = regs["HASHC"]
    NS["ROOM"] = (at[0] + 0xFFFF) & ~0xFFFF

