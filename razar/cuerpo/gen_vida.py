ld("j1", "WALK"); J("jjz j1, fr_alive", "jldi j10, 1", "jsub j1, j1, j10"); st("j1", "WALK")
o("fr_alive:                       ; alive while one arrives, one waits to, a lesson is pending, a gesture walks, a")
o("                                ; particle moves")
ld("j1", "ARRIVING"); J("jldi j10, 1", "jadd j1, j1, j10")
ld("j2", "N"); ld("j3", "NEXTK"); J("jsub j2, j2, j3", "jor j1, j1, j2")
