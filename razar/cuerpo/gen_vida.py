o("; ---- the living loop: wait for an event or for the frame's time, then a frame (as vivo.jsm)")
o("main:")
ld("j12", "REMAIN"); ld("j9", "FOREVER"); J("jjz j9, main_wait", "jldi j12, -1")
o("main_wait:")
J("jldi j10, 41"); li("j11", EV); J("jcall r_tocar"); st("j12", "BLEFT")
J("jjn j13, main_bad", "jjz j13, main_time")
st("j14", "CHANGED"); J("jcall r_handle")
ld("j9", "FOREVER"); J("jjz j9, main_timed_ev")
ld("j9", "CHANGED"); J("jjz j9, main"); st("j14", "FOREVER"); J("jjmp frame")
o("main_timed_ev:")
ld("j12", "BLEFT"); st("j12", "REMAIN"); J("jjz j12, frame", "jjmp main")
o("main_time:")
ld("j9", "FOREVER"); J("jjz j9, frame")
ld("j0", "KEPT"); J("jhalt                         ; for ever ran out: no window to wait on (JANAX_SIN_VENTANA)")
o("main_bad:")
J("jldi j0, 0BADh", "jhalt")
o("r_handle:                       ; 5 closed: the end. A button down or a key: a gesture")
ld("j9", EV); J("jldi j10, 5", "jsub j10, j9, j10", "jjnz j10, hd_open")
ld("j0", "KEPT"); J("jhalt")
o("hd_open:")
J("jldi j10, 2", "jsub j10, j9, j10", "jjz j10, hd_gesture", "jldi j10, 4", "jsub j10, j9, j10", "jjz j10, hd_gesture", "jret")
o("hd_gesture:                     ; they walk one period of the slowest gait among those here")
ld("j1", "PMAXF"); J("jldi j10, %d" % FRAME_MS, "jdiv j1, j1, j10", "jldi j10, 1", "jadd j1, j1, j10"); st("j1", "WALK")
setg("CHANGED", 1); st("j14", "QUIET"); J("jret")

o("; ---- one frame: an arrival, the walk, the particles, the picture")
o("frame:")
incg("FRAMES")
o("  ; the one arriving has landed: it joins, and the judge looks at it and every one here")
ld("j1", "ARRIVING"); J("jjn j1, fr_next"); rec("j9", "j1"); J("jld j2, j9, %d" % C_UNSET, "jjnz j2, fr_next")
J("jldi j2, 2", "jst j2, j9, %d" % C_STATE); st("j9", "TI"); J("jcall r_rowcol"); setg("ARRIVING", -1); st("j14", "QUIET")
o("fr_next:")
ld("j1", "ARRIVING"); J("jjnn j1, fr_walk")
o("fr_arrive:")
ld("j1", "NEXTK"); ld("j2", "N"); J("jsub j10, j1, j2", "jjnn j10, fr_walk")
ld("j3", "FB"); J("jmul j3, j3, j1"); ld("j10", "FA"); J("jadd j3, j3, j10", "jdiv j4, j3, j2", "jmul j4, j4, j2", "jsub j3, j3, j4")
st("j3", "IDX"); incg("NEXTK"); J("jcall r_arrive", "jjz j0, fr_arrive")
ld("j1", "IDX"); st("j1", "ARRIVING")
o("fr_walk:")
o("  ; a lesson is searched for while something new happened within the time the average walker here needs to")
o("  ; cross the world (W / mean speed): longer than that with nothing new, the ones left live apart")
J("jcall r_searching", "jjnz j0, fr_go"); ld("j1", "WALK"); J("jjz j1, fr_parts")
o("fr_go:")
J("jcall r_walk_all")
o("  ; the search's time: W / the mean speed of those here (frames)")
ld("j1", "VCNT"); ld("j2", "VSUM"); J("jjz j2, fr_vs0"); li("j10", W * 65536); J("jmul j1, j1, j10", "jdiv j1, j1, j2", "jjmp fr_vs")
o("fr_vs0:")
J("jldi j1, 0")
o("fr_vs:")
st("j1", "SEARCH")
o("  ; something new (a piece kept) wakes the search again")
ld("j1", "KEPT"); ld("j2", "LASTK"); st("j1", "LASTK"); J("jsub j1, j1, j2", "jjz j1, fr_q"); st("j14", "QUIET"); J("jjmp fr_parts")
