"""Generates vida.jsm: Gotching's creatures living together, as in Conway's game of Life (Capitan: "that LUMA learns
to treat the creatures as in the game of LIFE: that each one moves freely, that they meet, that they part, that they
share").

Every creature enters the window as a small body made of its own cloud's particles (its .nube, as the meals) and walks
by its own gait: the rhythms a bat instrument heard in its animation (its .oido: per limb a period, an amplitude and a
phase). Only local rules, as in Life or in boids: each one sees the others within a radius relative to its body.

THE GAIT, DESCRIBED (Razar's judge, MDL, in whole bits). A limb's rhythm is three integers: its period in ms, its
amplitude as a half-octave code (q = round(2 log2 a), a in the file's own unit, 1e-5 rad: the 5 decimals it prints) and
its phase in sixteenths of a turn, relative to the creature's widest limb (the recording's start is arbitrary, the
relations between limbs are the gait). A creature describes its gait with a model of K motifs (rhythms):
  DL = gamma(K) + sum over motifs (gamma(P) + gamma(q) + 4)
     + sum over limbs (bitlen(K) + min(literal: gamma(P) + gamma(q) + 4, best motif: gamma(zz dP) + gamma(zz dq) +
       gamma(zz ds)))
with gamma the Elias gamma code of n >= 0 (2 bitlen(n + 1) - 1 bits) and zz the zigzag of a signed difference. Its first
model is the greedy one built from its own limbs (add the limb that shortens DL most, while one does).
A creature MOVES by its model: each limb swings with the rhythm its description gives it (its motif, or itself), and
by Gotching's rule (razar/jueces/marcha_regla.py) the group of limbs that weighs more by amplitude, those that step on
the floor or those that do not, moves the body. The file's "dice" and "pares" lines are not used (measured unreliable).

THE LOCAL RULES. i is drawn to a neighbour j when a piece of j's gait (a rhythm j's body shows) would describe i's gait
in fewer bits (j has something to teach i), or the other way round (i has something to teach j); when neither, i drifts
away from j. When two touch, the pupil tries every piece of the teacher's gait (added as a motif, or in place of each of
its own); it keeps the best only if its description gets shorter. Every other piece goes to the archive with its
reason (nothing is discarded) and so does a motif it replaced; its motion changes with its new model, and with nothing
left to teach each other, they part.

NO WASTEFUL LOOP. It lives while something new happens: an arrival, a share, a gesture. A pending lesson is searched
for (they walk) while something new happened within the time the average walker needs to cross the world (W / mean
speed); after that the pairs left live apart. With every creature arrived and no search left, it calms and waits for
ever (request 41, 0 CPU) until a gesture, which makes them walk one period of the slowest gait and opens a new search.

Python generates the program and nothing else: the creatures are read at run time (request 37, read only) from the
list vida.sh writes into its folder ("lista"); the program carries no creature name. Files in its folder: "lista",
"aprendido" (the models learned, rewritten after each share) and "archivo" (a line per piece tried, only appended).
Ends when the window is closed: j0 = the pieces kept in this run. Generated by gen_vida.py."""
import math, os

AQUI = os.path.dirname(os.path.abspath(__file__))

# ---- the screen
W, H = 320, 200                   # cells; the window takes the largest whole scale that fits 1280 x 800 (4)
CLOUD = 0x10004                   # so that the colours start 8-aligned: they are cleared with 8-byte stores
BITS = CLOUD + 28
RGB = BITS + W * H // 8
TOTAL = 28 + W * H // 8 + 3 * W * H
assert RGB % 8 == 0
ROOM = (RGB + 3 * W * H + 0xFFFF) & ~0xFFFF
BACKGROUND = (0x14, 0x22, 0x26)
QUEUE, EV = 0x100, 0x140
SIN = 0x800                       # 256 qwords: sin(2 pi k / 256) x 4096
AMPT = 0x1000                     # 64 qwords: the amplitude of a half-octave code, round(2^(q/2)) in 1e-5 rad
AMPTH = 0x1200                    # 64 qwords: the thresholds, ceil(2^((q + 0.5)/2)); q = how many a reaches
QMAX = 63
LBL_L, LBL_A, LBL_R = 0x1400, 0x1410, 0x1420      # "lista", "aprendido", "archivo"
VERD = 0x1440                     # the verdicts, 16 bytes each
VERDICTS = ["kept", "replaced", "longer", "beaten"]
HDRB = 0x1500                     # the list's header
ALINE = 0x1580                    # an archive line
RECLEN = 80
GACC = 0x2700  # 8 qwords: per group (floor 1, air 0) speed, amp sum, lean, count
SCR = 0x1600                      # 4096 bytes to read a file through (its size, the archive's end)
SCRN = 4096
GV = 0x200

# ---- the model of the world. Every number says what it measures, or is marked criterion.
FRAME_MS = 33                     # one frame while something lives (~30 fps; the host's waits come in ~15.6 ms steps)
DENS = 4                          # the screen holds DENS bodies of area B^2 per creature, and the radius is 3 bodies:
RADIUS_B = 3                      #   pi 3^2 / 4 = 7 neighbours in sight on average, the 6-7 topological neighbours
                                  #   starlings keep (Ballerini et al., PNAS 2008). The body side B is solved from it:
                                  #   B = isqrt(W H / (DENS N)), so it is relative to how many there are.
BMIN, BMAX = 4, 40                # criterion: under 4 cells a body is no silhouette; 40 = an eighth of the width
TOUCH_B = 1                       # two touch when their centres are within one body (their boxes overlap)
TURN = 64                         # criterion: a quarter of the heading (256) turns to the steering each frame
WANDER = 8                        # criterion: Reynolds' wander, a random turn of at most 8/256 rad per frame
FALL_B = 4                        # an arrival falls in from 4 bodies above its place (criterion: seen falling)
LERP_SHIFT = 2                    # a particle covers 1/4 of the way to its place each frame (criterion: the jelly's
                                  #   ~4-frame time constant)
NPACK = 64                        # criterion: at most 64 packets of an exchange in the air at once (a share sends 2)
PK = 3                            # criterion: a packet is drawn 3 x 3 cells, seen at B = 8
PSZK = 80                         # a packet: active, x0, y0, dx, dy (x256), t, dur, P, s, colour (qwords)
REST = 32                         # 1/8 cell: closer than that a particle snaps to its place (as vivo.jsm)
# speed: a limb of length B/2 swinging with amplitude A (rad) and period P moves its tip at (B/2) A (2 pi / P) |cos|;
# the body advances at that speed, summed over the limbs of the group that moves it (see r_gait). Per frame, in
# cells x 65536: v = (B A |cos| >> 12) * V_K / (P * 1e5), V_K = 128 * 2 pi * FRAME_MS * 256 (A in 1e-5 rad, cos x 4096)
V_K = round(128 * 2 * math.pi * FRAME_MS * 256)
TWO_PI_E5 = 628319                # 2 pi in the file's unit (1e-5 rad)
HALF_SECTOR = TWO_PI_E5 // 2      # round(F 16 / 2pi) = floor((16 F + pi e5) / 2pi e5)
SEED = 0x2545F4914F6CDD1D
ORDER_SEED = 0x9E3779B97F4A7C15   # the order of the arrivals: its own generator
INF = 1 << 40
LHDR = 44                         # "lista1 N(6) NMAX(9) OMAX(9) TEXT(9)\n"
AHDR = 18                         # "aprendido1 NNNNNN\n"
MIN_LIMB_LINE = 48                # the shortest line of a rhythmic limb in a .oido: bounds the limbs per creature

# ---- the tables of a creature (qwords at these offsets)
C_ENT, C_STATE, C_CX, C_CY, C_HX, C_HY, C_L, C_K, C_NE, C_DL, C_LIMB, C_MOD, C_EFF, C_LEFF, C_ACC, C_PART, C_NP, \
    C_FNV, C_THETA, C_V, C_LEARN, C_LOADED, C_UNSET, C_PNUB, C_LNUB, C_BNUB, C_POID, C_LOID, C_BOID, C_TIDX = \
    [8 * k for k in range(30)]
CSZ = 8 * 32
RS = 32                           # a rhythm: P (ms), q, s (qwords); a limb adds whether it steps on the floor (pata)
PSZ = 48                          # a particle: home x, y, offset x, y (x256, from the centre), colour (r | g<<8 | b<<16)

L = []; o = L.append
n_label = [0]
def lab(s):
    n_label[0] += 1
    return "%s_%d" % (s, n_label[0])
def num(v):
    return ("0%Xh" % v) if v >= 10 else str(v)
def li(r, v):
    if -0x8000 <= v < 0x8000:
        o("  jldi %s, %s" % (r, str(v) if v < 0 else num(v))); return
    v &= (1 << 64) - 1
    parts = [(v >> s) & 0xFFFF for s in (48, 32, 16, 0)]
    while len(parts) > 1 and parts[0] == 0 and parts[1] < 0x8000:
        parts.pop(0)
    while len(parts) > 1 and parts[0] == 0xFFFF and parts[1] >= 0x8000:
        parts.pop(0)
    first = parts[0] - 0x10000 if parts[0] >= 0x8000 else parts[0]
    o("  jldi %s, %s" % (r, str(first) if first < 0 else num(first)))
    for p in parts[1:]:
        o("  jshi %s, %s" % (r, num(p)))
def J(*xs):
    for x in xs:
        o("  " + x)

VARS = ("REMAIN FOREVER BLEFT CHANGED RNG N B R2 RB TB LM CR GAIN PARTS LIST LTXT NMAX OMAX NUBB OIDB TMPM PIECEM "
        "BESTM ACC VBUF VCAP VLEN NEXTK FA FB ARRIVING TEACH WALK MOVING KEPT ARCH FRAMES FH AH Q1 Q2 Q3 Q4 Q5 Q6 Q7 "
        "Q8 Q9 TI TJ PP TBEST TBK TBR GBEST SBEST SBK SBR SBP SBI NW NH NBITS NRGB SN SD OFX OFY STX STY SVX SVY "
        "DX DY DD PMAXF IDX FNVP ALIVE WI SJ SG SQ4 SHJ BLIMB BMOD BEFF BLEFF BACC GW GH GCW GCH HEAD NEXT SCX SCY SOX SOY SNX SNY QUIET LASTK SEARCH VSUM VCNT PACK FLIVE").split()
G = {n: GV + 8 * i for i, n in enumerate(VARS)}
assert max(G.values()) < SIN
def ld(r, n): o("  jld %s, j14, %s" % (r, num(G[n] if isinstance(n, str) else n)))
def st(r, n): o("  jst %s, j14, %s" % (r, num(G[n])))
def setg(n, v): li("j10", v); st("j10", n)
def incg(n, by=1): ld("j10", n); li("j11", by); J("jadd j10, j10, j11"); st("j10", n)
def rec(r, idx):
    """r = the record of creature idx (a register); uses j10."""
    J("jldi j10, %d" % CSZ, "jmul %s, %s, j10" % (r, idx)); ld("j10", "CR"); J("jadd %s, %s, j10" % (r, r))
def put_string(addr, s, width):
    for i, b in enumerate(s.encode().ljust(width, b" ")):
        J("jldi j1, %s" % num(b), "jstb j1, j14, %s" % num(addr + i))

for line in __doc__.strip().split("\n"):
    o("; " + line if line else ";")
o("include '../../escalon0/janax.inc'")
o("jfirst j1, %Xh" % ROOM)
o("jldi j14, 0                     ; j14 stays 0: the variables live below 8000h")
cabeza = b"NUBE" + bytes([3]) + b"\x00\x00\x80\x3f" + b"\x00\x00" + bytes([1]) + b"\x00\x00\x80\x3f" + bytes(8) + \
    W.to_bytes(2, "little") + H.to_bytes(2, "little")
assert len(cabeza) == 28
o("; ---- the screen's cloud: its header and every cell set, once")
li("j1", CLOUD)
for i, b in enumerate(cabeza):
    J("jldi j2, %s" % num(b), "jstb j2, j1, %d" % i)
li("j1", BITS); li("j2", BITS + W * H // 8); J("jldi j3, -1", "jldi j4, 1")
o("init_bits:")
J("jstb j3, j1, 0", "jadd j1, j1, j4", "jsub j5, j2, j1", "jjnz j5, init_bits")
o("; ---- the tables: sine, the amplitude of each half-octave code and its thresholds (data, from the generator)")
for k in range(256):
    li("j1", round(4096 * math.sin(2 * math.pi * k / 256))); o("  jst j1, j14, %s" % num(SIN + 8 * k))
for q in range(64):
    li("j1", round(2 ** (q / 2))); o("  jst j1, j14, %s" % num(AMPT + 8 * q))
    li("j1", math.ceil(2 ** ((q + 0.5) / 2))); o("  jst j1, j14, %s" % num(AMPTH + 8 * q))
put_string(LBL_L, "lista", 5); put_string(LBL_A, "aprendido", 9); put_string(LBL_R, "archivo", 7)
for i, v in enumerate(VERDICTS):
    put_string(VERD + 16 * i, v, 8)
setg("RNG", SEED); setg("ARRIVING", -1)
J("jcall r_load_list", "jcall r_load_learned", "jcall r_open_archive")
o("; ---- the order of the arrivals: a start and a stride coprime to N, from its own generator (each one once)")
ld("j1", "N"); J("jjz j1, order_done")
setg("RNG", ORDER_SEED)
ld("j1", "N"); J("jcall r_randmod"); st("j0", "FA")
ld("j1", "N"); J("jcall r_coprime"); st("j0", "FB")
setg("RNG", SEED)
o("order_done:")
J("jjmp frame")

